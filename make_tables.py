"""
make_tables.py -- 从结果 JSON 自动生成论文 LaTeX 表格（tables/*.tex）。

原则：论文中的每个数字都由本脚本从原始 JSON 计算，禁止手抄。

生成：
  tables/main_imagenet.tex   Table 1  ImageNet 主对比（9 方法 + ceiling，全黑盒均值）
  tables/clipdown_delta.tex  Table 2  clip-down 反驳实验配对 Δ
  tables/cifar_control.tex   Table 3  CIFAR 对照（results_cifar_control 存在时生成）

用法: python make_tables.py
"""
import glob
import json
import os

import numpy as np

EPS = [0.1, 0.2, 0.3]
IMAGENET_MODELS = ["resnet50", "vgg16_bn", "resnet101", "mobilenet_v2", "vit_b_16"]
SURR = ["resnet50", "resnet101", "vit_b_16"]
SEEDS = [42, 1342, 2342]

# 论文显示名（去内部代号）。引用键已核实（2026-10-30）：
#   ffa = Mopuri et al., BMVC 2017；ssa_energy = Mopuri et al., TPAMI 2019
DISPLAY = {
    "reuse_lws": "Scale-up (SGD)",
    "reuse_tsc": "Scale-up (TSC)",
    "direct": "Direct ($\\epsilon$-per-run)",
    "direct_lr0.05": "Direct (lr 0.05)",
    "uap2017": "UAP~\\cite{moosavi2017universal}",
    "ffa": "FFA~\\cite{mopuri2017ffa}",
    "ssa_energy": "SSA~\\cite{mopuri2019generalizable}",
    "tsc": "TSC-UAP~\\cite{huang2024texture}",
    "dmuap": "DM-UAP~\\cite{zhang2025dmuap}",
    "ceiling": "Ceiling (2000-shot)",
}


def load_sota():
    runs = {}
    for f in glob.glob("results_fewshot_sota/*.json"):
        j = json.load(open(f))
        if j.get("surrogate") in SURR and j.get("seed") in SEEDS:
            runs[(j["surrogate"], j["seed"])] = j
    return runs


