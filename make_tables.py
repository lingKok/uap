def t7_svd(runs_sota, outdir):
    """P1: SVD 方向基线（Khrulkov-Babu，零优化）vs 优化方向，ResNet-50 surrogate。

    数据: results_svduap/results_svduap_imagenet_resnet50_seed<seed>.json (3 seeds)。
    对照组 scale-up/direct 取自 results_fewshot_sota 的 resnet50 子集（同 3 seeds）。
    """
    runs_sv = load_svduap()
    if not runs_sv:
        _write(outdir, "svd_baseline.tex", [
            "% AUTO-GENERATED placeholder -- results_svduap/ is empty",
            "\\begin{table}[t]\\centering",
            "\\caption{SVD direction baseline (pending).}",
            "\\label{tab:svd}",
            "\\begin{tabular}{l}", "\\toprule",
            "TODO: run the SVD slurm script \\\\",
            "\\bottomrule", "\\end{tabular}\\end{table}", ""])
        return
    runs_r50 = {k: j for k, j in runs_sota.items() if k[0] == "resnet50"}
    sv_names = sorted({m for j in runs_sv.values() for m in j["methods"]})

    def bb_sv(j, m, e):
        v = [fr_cd(j, m, e, t) for t in IMAGENET_MODELS if t != "resnet50"]
        return float(np.nanmean(v))

    def bb_r50(m, e):
        out = [bb(runs_r50, fr_sota, m, e, key=k) for k in sorted(runs_r50)]
        return float(np.nanmean(out))

    # 固定"最优配置"（跨全预算黑盒均值最高），delta 行用它
    def cfg_mean(m):
        return float(np.mean([bb_sv(j, m, e) for j in runs_sv.values() for e in EPS]))
    best_cfg = max(sv_names, key=cfg_mean)

    tex = [
        "% AUTO-GENERATED by make_tables.py -- DO NOT EDIT BY HAND",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{SVD direction baseline (ResNet-50 surrogate, black-box"
        " mean over the 4 remaining targets, 3 seeds). The singular-vector"
        " direction of~\\cite{khrulkov2018art} uses no optimization at all"
        " ($k{\\in}\\{64,200\\}$ images, top right singular vector of the"
        " layer Jacobian; rows ``layer2''/``layer4'' denote the layer whose"
        " Jacobian is decomposed) and is budget-agnostic by construction"
        " ($\\delta(\\epsilon){=}\\epsilon\\,\\hat v$, exact at every"
        " $\\epsilon$). $\\Delta$: paired scale-up $-$ SVD difference (pp)"
        " for the best SVD configuration; t: paired $t$-statistic over"
        " 3 seeds.}",
        "\\label{tab:svd}",
        "\\small",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "Method & Opt.\\ runs & $\\epsilon{=}0.1$ & $\\epsilon{=}0.2$ & $\\epsilon{=}0.3$ \\\\",
        "\\midrule",
        f"Scale-up (SGD) & 1 & {bb_r50('reuse_lws', 0.1)*100:.1f}"
        f" & {bb_r50('reuse_lws', 0.2)*100:.1f} & {bb_r50('reuse_lws', 0.3)*100:.1f} \\\\",
        f"Direct & 3 & {bb_r50('direct', 0.1)*100:.1f}"
        f" & {bb_r50('direct', 0.2)*100:.1f} & {bb_r50('direct', 0.3)*100:.1f} \\\\",
        "\\midrule",
    ]
    def svd_display(m):
        """svd_k64_layer4 -> SVD ($k{=}64$, layer 4)；防裸下划线进 text mode。"""
        import re as _re
        mm = _re.match(r"svd_k(\d+)_(.+)", m)
        if mm:
            return f"SVD ($k{{=}}{mm.group(1)}$, {mm.group(2)})"
        return m.replace("_", "\\_")

    for m in sv_names:
        agg = [float(np.mean([bb_sv(j, m, e) for j in runs_sv.values()])) for e in EPS]
        star = " (best)" if m == best_cfg else ""
        tex.append(f"{svd_display(m)}{star} & 0 & "
                   + " & ".join(f"{c*100:.1f}" for c in agg) + " \\\\")
    tex.append("\\midrule")
    cells, ts = [], []
    for e in EPS:
        d = paired_delta(runs_r50, fr_sota, "reuse_lws", runs_sv, fr_cd, best_cfg, e) * 100
        cells.append(f"{d.mean():+.1f}")
        ts.append(fmt_t(d))
    tex.append(f"$\\Delta$: Scale-up $-$ SVD (best) & -- & "
               + " & ".join(f"{c} ({t})" for c, t in zip(cells, ts)) + " \\\\")
    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    _write(outdir, "svd_baseline.tex", tex)


def t8_p2(outdir):
    """P2: 现代架构评估目标扩容（ConvNeXt-T/Swin-T/EffNet-B0），resnet50 surrogate。

    数据: results_p2/results_p2_imagenet_resnet50_seed<seed>.json (3 seeds)。
    每个方法 x eps 在全部 8 目标上评估；本表展示 3 个新目标（原 5 列为
    重训一致性参照，完整网格在 json）。
    """
    files = sorted(glob.glob("results_p2/*.json"))
    if not files:
        _write(outdir, "p2_targets.tex", [
            "% AUTO-GENERATED placeholder -- results_p2/ is empty",
            "\\begin{table}[t]\\centering",
            "\\caption{Modern-architecture evaluation targets (pending).}",
            "\\label{tab:p2}",
            "\\begin{tabular}{l}", "\\toprule",
            "TODO: run the P2 slurm script \\\\",
            "\\bottomrule", "\\end{tabular}\\end{table}", ""])
        return
    runs = {}
    for f in files:
        j = json.load(open(f))
        runs[j["seed"]] = j
    NEW = ["convnext_tiny", "swin_t", "efficientnet_b0"]

    def cell(m, e, ts):
        return float(np.mean([
            np.nanmean([j["methods"][m][str(e)][t]["fr_all"] for t in ts])
            for j in runs.values()]))

    def paired(m_a, m_b, e):
        ds = []
        for j in runs.values():
            sa = np.nanmean([j["methods"][m_a][str(e)][t]["fr_all"] for t in NEW])
            sb = np.nanmean([j["methods"][m_b][str(e)][t]["fr_all"] for t in NEW])
            ds.append(sa - sb)
        return np.array(ds) * 100

    tex = [
        "% AUTO-GENERATED by make_tables.py -- DO NOT EDIT BY HAND",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Modern-architecture evaluation targets (ResNet-50"
        " surrogate, 3 seeds, 200-shot protocol of"
        " Table~\\ref{tab:protocol}). Three 2020+ targets are added to the"
        " pool: ConvNeXt-T, Swin-T, EfficientNet-B0; all methods are"
        " retrained under the identical protocol (fresh runs; the repeated"
        " old-pool measurements reproduce the ResNet-50 rows of"
        " Table~\\ref{tab:main-imagenet}"
        " within 0.7pp). ``New-mean'': mean over the 3 new targets."
        " $\\Delta$ rows: paired difference (pp) on the new-target mean"
        " per budget, with paired $t$ over 3 seeds.}",
        "\\label{tab:p2}",
        "\\small",
        "\\begin{tabular}{llcccc}",
        "\\toprule",
        "Method & $\\eps$ & ConvNeXt-T & Swin-T & EffNet-B0 & New-mean \\\\",
        "\\midrule",
    ]
    show = [("Scale-up (SGD)", "reuse_lws"), ("Scale-up (TSC)", "reuse_tsc"),
            ("Direct", "direct"), ("TSC-UAP", "tsc")]
    for disp, m in show:
        for e in [0.1, 0.2, 0.3]:
            cells = [cell(m, e, [t]) for t in NEW] + [cell(m, e, NEW)]
            tex.append(f"{disp} & {e:.1f} & "
                       + " & ".join(f"{c*100:.1f}" for c in cells) + " \\\\")
        tex.append("\\midrule")
    tex.pop()
    disp_of = {m: d for d, m in show}
    for la, lb in [("reuse_lws", "direct"), ("reuse_tsc", "tsc")]:
        na = disp_of[la]
        nb = disp_of[lb]
        for e in [0.1, 0.2, 0.3]:
            d = paired(la, lb, e)
            tex.append(f"$\\Delta$: {na} $-$ {nb} & {e:.1f} & & & & "
                       f"{d.mean():+.1f} ({fmt_t(d)}) \\\\")
    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    _write(outdir, "p2_targets.tex", tex)


