def fr_sota(j, m, e, t):
    if m == "ceiling":
        return j["ceiling"][str(e)][t]["fr_all"]
    src = j["methods"] if m in j.get("methods", {}) else j["ceiling"]
    key = m if m in src else "ceiling"
    return src[key][str(e)][t]["fr_all"]


def fr_cd(j, m, e, t):
    return j["methods"][m][str(e)][t]["fr_all"]


def bb(runs, fr_fn, m, e, key=None):
    """某 (surrogate,seed) 的全黑盒均值；key=None 时跨全部 run 平均。"""
    out = []
    for k, j in runs.items():
        if key is not None and k != key:
            continue
        v = [fr_fn(j, m, e, t) for t in IMAGENET_MODELS if t != j["surrogate"]]
        out.append(float(np.nanmean(v)))
    return float(np.nanmean(out))


def paired_delta(runs_a, fa, m_a, runs_b, fb, m_b, e):
    """seed 级配对 delta：a − b，按 (surrogate, seed) 对齐。返回 array。"""
    ds = []
    for k in sorted(set(runs_a) & set(runs_b)):
        ta = [fa(runs_a[k], m_a, e, t) for t in IMAGENET_MODELS if t != k[0]]
        tb = [fb(runs_b[k], m_b, e, t) for t in IMAGENET_MODELS if t != k[0]]
        ds.append(np.nanmean(ta) - np.nanmean(tb))
    return np.array(ds)


def fmt_t(d):
    if len(d) < 2 or d.std(ddof=1) == 0:
        return "--"
    return f"{d.mean() / (d.std(ddof=1) / np.sqrt(len(d))):+.1f}"


def t1_main_imagenet(runs, outdir):
    methods = ["reuse_lws", "reuse_tsc", "direct", "direct_lr0.05",
               "uap2017", "ffa", "ssa_energy", "tsc", "dmuap"]
    rows = []
    for m in methods:
        cells = [bb(runs, fr_sota, m, e) for e in EPS]
        rows.append((m, cells))
    ceil = [bb(runs, fr_sota, "ceiling", e) for e in EPS]

    cost = {"reuse_lws": "1$\\times$", "reuse_tsc": "1$\\times$",
            "direct": "3$\\times$", "direct_lr0.05": "3$\\times$",
            "uap2017": "3$\\times$", "ffa": "3$\\times$", "ssa_energy": "3$\\times$",
            "tsc": "3$\\times$", "dmuap": "3$\\times$ (3.3$\\times$/run)"}
    best = [max(r[1][i] for r in rows) for i in range(3)]

    tex = [
        "% AUTO-GENERATED by make_tables.py -- DO NOT EDIT BY HAND",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{ImageNet: black-box fooling rate (\\%) of one UAP shared across"
        " all transfer targets, mean over 3 surrogates $\\times$ 3 seeds $\\times$"
        " heterogeneous targets (200-shot training data). Ceiling: 2000-shot"
        " multi-step reference attack (not a theoretical bound). DM-UAP receives"
        " $3.3\\times$ more wall-clock per run (measured). Cells are rounded to"
        " one decimal, so a paired $\\Delta$ quoted in the text can differ from"
        " the difference of two displayed cells by $0.1$\\,pp.}",
        "\\label{tab:main-imagenet}",
        "\\small",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "Method & Train runs & $\\epsilon{=}0.1$ & $\\epsilon{=}0.2$ & $\\epsilon{=}0.3$ \\\\",
        "\\midrule",
    ]
    for m, cells in rows:
        cells_pct = [f"\\textbf{{{c*100:.1f}}}" if abs(c - b) < 1e-9 else f"{c*100:.1f}"
                     for c, b in zip(cells, best)]
        tex.append(f"{DISPLAY[m]} & {cost[m]} & " + " & ".join(cells_pct) + " \\\\")
    tex.append("\\midrule")
    tex.append(f"{DISPLAY['ceiling']} & -- & " +
               " & ".join(f"{c*100:.1f}" for c in ceil) + " \\\\")
    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    _write(outdir, "main_imagenet.tex", tex)
    return rows, ceil


def t2_clipdown(runs_sota, runs_cd, outdir):
    """clip-down 反驳实验：Δ = clipdown − {pereps, scaleup}，seed 级配对。"""
    scaleup_of = {"direct": ("reuse_lws", runs_sota, fr_sota),
                  "tsc": ("reuse_tsc", runs_sota, fr_sota)}
    tex = [
        "% AUTO-GENERATED by make_tables.py -- DO NOT EDIT BY HAND",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{ImageNet clip-down counterfactual: paired difference"
        " $\\Delta$ (pp) of training once at $\\epsilon_{\\max}{=}0.3$ and clipping"
        " down, vs.\\ per-$\\epsilon$ retraining (upper block) and vs.\\ scale-up"
        " (lower block; one training at $\\epsilon_w{=}0.05$). $n{=}9$ paired runs;"
        " negative $\\Delta$ favours the alternative. t: paired $t$-statistic."
        " Entries with $|\\Delta|\\lesssim1.2$\\,pp fall inside the cross-job"
        " reproducibility floor (Sec.~\\ref{sec:limits}) and are read as"
        " ties; the mechanism claim rests on the between-optimizer contrast, not"
        " on any single small entry.}",
        "\\label{tab:clipdown}",
        "\\small",
        "\\begin{tabular}{llccc}",
        "\\toprule",
        "Optimizer & Comparison & $\\epsilon{=}0.1$ & $\\epsilon{=}0.2$ & $\\epsilon{=}0.3$ \\\\",
        "\\midrule",
    ]
    for m in ["direct", "tsc", "uap2017", "dmuap"]:
        cells, ts = [], []
        for e in EPS:
            d = paired_delta(runs_cd, fr_cd, m, runs_sota, fr_sota, m, e) * 100
            cells.append(f"{d.mean():+.1f}")
            ts.append(fmt_t(d))
        tex.append(f"{DISPLAY[m]} (clip-down) & vs.\\ per-$\\epsilon$ & "
                   + " & ".join(f"{c} ({t})" for c, t in zip(cells, ts)) + " \\\\")
    tex.append("\\midrule")
    for m, (mu, rb, fb) in scaleup_of.items():
        cells, ts = [], []
        for e in EPS:
            d = paired_delta(runs_cd, fr_cd, m, rb, fb, mu, e) * 100
            cells.append(f"{d.mean():+.1f}")
            ts.append(fmt_t(d))
        tex.append(f"{DISPLAY[m]} (clip-down) & vs.\\ scale-up & "
                   + " & ".join(f"{c} ({t})" for c, t in zip(cells, ts)) + " \\\\")
    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    _write(outdir, "clipdown_delta.tex", tex)


def t3_cifar_control(outdir):
    files = sorted(glob.glob("results_cifar_control/*.json"))
    if not files:
        _write(outdir, "cifar_control.tex", [
            "% AUTO-GENERATED placeholder — results_cifar_control/ 尚无数据",
            "\\begin{table}[t]\\centering",
            "\\caption{CIFAR-10 control (pending).}",
            "\\label{tab:cifar}",
            "\\begin{tabular}{l}", "\\toprule", "TODO: run slurm_cifar_control.sh \\\\",
            "\\bottomrule", "\\end{tabular}\\end{table}", ""])
        return
    runs = {}
    for f in files:
        j = json.load(open(f))
        runs[(j["surrogate"], j["seed"])] = j
    methods = sorted({m for j in runs.values() for m in j["methods"]})
    tex = [
        "% AUTO-GENERATED by make_tables.py -- DO NOT EDIT BY HAND",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{CIFAR-10 control (FR-ceiling-bound regime): black-box fooling"
        " rate (\\%), same protocol as the ImageNet experiments"
        " (Table~\\ref{tab:protocol}). Every method,"
        " budget, and deployment strategy converges to the same irreducible"
        " ceiling ($\\approx$91\\%), so the three strategies coincide---the"
        " advantage is conditioned on the ceiling being unbinding.}",
        "\\label{tab:cifar}",
        "\\small",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "Method & $\\epsilon$ & per-$\\epsilon$ & clip-down & scale-up \\\\",
        "\\midrule",
    ]
    for m in methods:
        for i, e in enumerate([0.1, 0.2, 0.3]):
            cells = []
            for st in ["pereps", "clipdown", "scaleup"]:
                acc = []
                for j in runs.values():
                    if m not in j["methods"] or str(e) not in j["methods"][m]:
                        continue
                    v = [j["methods"][m][str(e)][st][t]["fr_all"]
                         for t in j["methods"][m][str(e)][st] if t != j["surrogate"]]
                    acc.append(np.nanmean(v))
                cells.append(f"{np.nanmean(acc)*100:.1f}")
            name = DISPLAY.get(m, m) if i == 0 else ""
            tex.append(f"{name} & {e:.1f} & " + " & ".join(cells) + " \\\\")
        tex.append("\\midrule")
    if tex[-1] == "\\midrule":
        tex.pop()
    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    _write(outdir, "cifar_control.tex", tex)


# 天然宽度 <= ~205pt（sigconf 单栏 247pt）的表用单栏浮动体；宽表用 table*。
# 依据 2026-11-01 编译 PDF 的实测规则线宽度（PyMuPDF 量 booktabs 横线）：
#   ksweep 192 / bsweep 172 / cost 195 / p2 202 / protocol 139 -> 单栏
#   main 311 / clipdown 301 / epsw 293 / svd 292 / cifar 292 / l2 305 /
#   permodel 310 -> 跨栏（单栏放不下，clipdown 想进单栏需 \footnotesize+压
#   tabcolsep，勉强 ~238pt，可读性差，暂不做）
SINGLE_COL = {"suppl_ksweep.tex", "suppl_bsweep.tex",
              "cost_accounting.tex", "suppl_l2.tex"}


def _write(outdir, name, lines):
    """写表。ACM sigconf 双栏：默认输出跨栏 table*；SINGLE_COL 里的窄表输出
    单栏 table（只改浮动体环境名，数字与逻辑不变）。"""
    os.makedirs(outdir, exist_ok=True)
    path = os.path.join(outdir, name)
    text = "\n".join(lines)
    if name in SINGLE_COL:
        text = text.replace("\\begin{table*}[t]", "\\begin{table}[t]")
        text = text.replace("\\end{table*}", "\\end{table}")
    else:
        text = text.replace("\\begin{table}[t]", "\\begin{table*}[t]")
        text = text.replace("\\end{table}", "\\end{table*}")
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"[写入] {path} ({len(lines)} 行)")


def t4_cost(runs_sota, outdir):
    """算力表：覆盖三个预算的总训练时长（实测秒，json meta 自报）。"""
    import statistics
    rows = [("Scale-up (SGD)", "reuse_train_time_w", 1),
            ("Scale-up (TSC)", "reuse_tsc_train_time_w", 1),
            ("Direct ($\\epsilon$-per-run)", "direct_train_time_total", 3),
            ("UAP~\\cite{moosavi2017universal}", "uap2017_train_time_total", 3),
            ("TSC-UAP~\\cite{huang2024texture}", "tsc_train_time_total", 3),
            ("DM-UAP~\\cite{zhang2025dmuap}", "dmuap_train_time_total", 3)]
    tex = [
        "% AUTO-GENERATED by make_tables.py -- DO NOT EDIT BY HAND",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Measured training compute (GPU-seconds, mean $\\pm$ sd"
        " over 9 runs, i.e., 3 surrogates $\\times$ 3 seeds; the spread is"
        " dominated by architecture cost differences, e.g., ViT trains"
        " $\\sim$4$\\times$ slower than ResNet-50) to cover all three budgets"
        " $\\epsilon\\in\\{0.1,0.2,0.3\\}$. Scale-up trains once at"
        " $\\epsilon_w{=}0.05$ and rescales; baselines train per budget"
        " (three runs). DM-UAP additionally uses $3.3\\times$ more compute"
        " \\emph{per run} by its official settings. The two cheaper entries are not"
        " FR-comparable to the scale-up instance we quote: UAP~\\cite{moosavi2017universal}"
        " ($1.8\\times$) trails it by $26.7$--$34.2$\\,pp and per-$\\epsilon$ SGD"
        " retraining ($2.9\\times$) by $22.7$--$29.3$\\,pp at every budget, so the"
        " $3.0\\times$--$9.7\\times$ range is restricted to FR-competitive baselines.}",
        "\\label{tab:cost}",
        "\\small",
        "\\begin{tabular}{lccr}",
        "\\toprule",
        "Method & Runs & GPU-s (total) & Rel.\\ scale-up \\\\",
        "\\midrule",
    ]
    base = {"reuse_train_time_w": [], "reuse_tsc_train_time_w": []}
    agg = {k: [] for _, k, _ in rows}
    for j in runs_sota.values():
        for k in agg:
            if k in j.get("meta", {}):
                agg[k].append(j["meta"][k])
    for name, key, runs in rows:
        v = agg[key]
        if not v:
            continue
        m = statistics.mean(v)
        sd = statistics.stdev(v) if len(v) > 1 else 0.0
        rel = m / statistics.mean(agg["reuse_train_time_w"])
        star = "" if runs == 1 else f"$^{{{runs}}}$"
        # 上标（run 数）贴在方法名后，避免与 sd 数字粘连被误读（如 146^3 -> 1463）
        tex.append(f"{name}{star} & {runs} & {m:,.0f} $\\pm$ {sd:,.0f} & "
                   f"{rel:.1f}$\\times$ \\\\")
    tex += ["\\bottomrule", "\\end{tabular}", "\\\\",
            "\\footnotesize $^{3}$: three per-budget runs; totals include all"
            " three. DM-UAP per-run wall-clock is $3.3\\times$"
            " scale-up's single run.", "\\end{table}", ""]
    _write(outdir, "cost_accounting.tex", tex)


